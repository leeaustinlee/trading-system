-- Narrative Intelligence Layer foundation.
--
-- This migration creates production-facing narrative_* tables while keeping the
-- existing kol_* MVP path intact. These tables are additive only: no BUY signal,
-- no risk gate override, no FinalDecisionEngine override.

CREATE TABLE IF NOT EXISTS narrative_signal (
    id                         BIGINT AUTO_INCREMENT PRIMARY KEY,
    trading_date               DATE          NOT NULL,
    source_key                 VARCHAR(160)  NOT NULL,
    source_type                VARCHAR(40)   NOT NULL,
    source_name                VARCHAR(200)  NULL,
    episode_id                 VARCHAR(160)  NULL,
    episode_title              VARCHAR(300)  NULL,
    source_url                 VARCHAR(1000) NULL,
    published_at               TIMESTAMP     NULL,
    ingested_at                TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    content_hash               CHAR(64)      NOT NULL,
    raw_content                MEDIUMTEXT    NULL,
    raw_content_path           VARCHAR(1000) NULL,
    ai_summary                 TEXT          NULL,
    extraction_status          VARCHAR(40)   NOT NULL DEFAULT 'RAW',
    extraction_model           VARCHAR(120)  NULL,
    extraction_prompt_version  VARCHAR(80)   NULL,
    mentioned_themes_json      JSON          NULL,
    mentioned_stocks_json      JSON          NULL,
    source_language            VARCHAR(20)   NULL,
    market_regime              VARCHAR(40)   NULL,
    freshness_score            DECIMAL(6,3)  NULL,
    conviction_score           DECIMAL(6,3)  NULL,
    uncertainty_score          DECIMAL(6,3)  NULL,
    crowding_score             DECIMAL(6,3)  NULL,
    confidence                 DECIMAL(6,3)  NULL,
    status                     VARCHAR(40)   NOT NULL DEFAULT 'ACTIVE',
    payload_json               JSON          NULL,
    created_at                 TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                 TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_narrative_content_hash (content_hash),
    KEY idx_narrative_date_source (trading_date, source_key),
    KEY idx_narrative_published (published_at),
    KEY idx_narrative_status (trading_date, extraction_status, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS theme_signal (
    id                       BIGINT AUTO_INCREMENT PRIMARY KEY,
    narrative_signal_id       BIGINT       NOT NULL,
    trading_date              DATE         NOT NULL,
    theme_tag                 VARCHAR(120) NOT NULL,
    theme_alias               VARCHAR(200) NULL,
    normalized_theme_id       BIGINT       NULL,
    direction                 VARCHAR(40)  NOT NULL DEFAULT 'UNKNOWN',
    tone                      VARCHAR(40)  NOT NULL DEFAULT 'MIXED',
    narrative_direction       VARCHAR(40)  NULL,
    lifecycle_hint            VARCHAR(40)  NULL,
    conviction_score          DECIMAL(6,3) NULL,
    freshness_score           DECIMAL(6,3) NULL,
    novelty_score             DECIMAL(6,3) NULL,
    uncertainty_score         DECIMAL(6,3) NULL,
    crowding_score            DECIMAL(6,3) NULL,
    evidence_level            VARCHAR(40)  NULL,
    evidence_weight           DECIMAL(6,3) NULL,
    confidence                DECIMAL(6,3) NULL,
    reason_summary            VARCHAR(1200) NULL,
    risk_summary              VARCHAR(1200) NULL,
    payload_json              JSON         NULL,
    created_at                TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    KEY idx_theme_signal_date_theme (trading_date, theme_tag),
    KEY idx_theme_signal_theme_date (theme_tag, trading_date),
    KEY idx_theme_signal_direction (trading_date, direction),
    CONSTRAINT fk_theme_signal_narrative
        FOREIGN KEY (narrative_signal_id) REFERENCES narrative_signal(id)
        ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

