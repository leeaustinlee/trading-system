    mention_frequency_score              DECIMAL(6,3) NOT NULL DEFAULT 0.000,
    source_density_score                 DECIMAL(6,3) NOT NULL DEFAULT 0.000,
    media_spread_score                   DECIMAL(6,3) NOT NULL DEFAULT 0.000,
    spread_velocity_score                DECIMAL(6,3) NOT NULL DEFAULT 0.000,
    price_extension_score                DECIMAL(6,3) NOT NULL DEFAULT 0.000,
    turnover_heat_score                  DECIMAL(6,3) NOT NULL DEFAULT 0.000,
    retail_crowding_score                DECIMAL(6,3) NOT NULL DEFAULT 0.000,
    institutional_participation_score    DECIMAL(6,3) NOT NULL DEFAULT 0.000,
    lifecycle_confidence                 DECIMAL(6,3) NULL,
    recommended_effect                   VARCHAR(80)  NOT NULL DEFAULT 'CONTEXT_ONLY',
    weight_factor                        DECIMAL(6,3) NOT NULL DEFAULT 1.000,
    sizing_factor                        DECIMAL(6,3) NOT NULL DEFAULT 1.000,
    entry_aggressiveness                 VARCHAR(40)  NOT NULL DEFAULT 'NORMAL',
    stop_strategy                        VARCHAR(80)  NOT NULL DEFAULT 'NORMAL',
    risk_flags_json                      JSON         NULL,
    evidence_json                        JSON         NULL,
    payload_json                         JSON         NULL,
